-- The schema of phases 1 and 2 with the row ids of SQLite's
-- migration 2. Text columns compare byte-wise (COLLATE "C") as
-- SQLite's do, so ORDER BY gives the same order on both. Times
-- are RFC 3339 text in UTC on both backends.
CREATE TABLE users(
  name TEXT COLLATE "C" PRIMARY KEY, token_sha256 TEXT COLLATE "C" NOT NULL UNIQUE,
  role TEXT COLLATE "C" NOT NULL, created_at TEXT COLLATE "C" NOT NULL);
CREATE TABLE files(
  path TEXT COLLATE "C" PRIMARY KEY, body BYTEA NOT NULL, sha256 TEXT COLLATE "C" NOT NULL,
  size BIGINT NOT NULL, updated_at TEXT COLLATE "C" NOT NULL, updated_by TEXT COLLATE "C" NOT NULL,
  version INTEGER NOT NULL DEFAULT 1);
CREATE TABLE file_versions(
  path TEXT COLLATE "C" NOT NULL, version INTEGER NOT NULL, body BYTEA NOT NULL,
  sha256 TEXT COLLATE "C" NOT NULL, size BIGINT NOT NULL, updated_at TEXT COLLATE "C" NOT NULL,
  updated_by TEXT COLLATE "C" NOT NULL, PRIMARY KEY(path, version));
CREATE TABLE hosts(
  name TEXT COLLATE "C" PRIMARY KEY, os TEXT COLLATE "C" NOT NULL DEFAULT '',
  ip TEXT COLLATE "C" NOT NULL DEFAULT '', distro TEXT COLLATE "C" NOT NULL DEFAULT '',
  tags TEXT COLLATE "C" NOT NULL DEFAULT '', owner TEXT COLLATE "C" NOT NULL DEFAULT '',
  services TEXT COLLATE "C" NOT NULL DEFAULT '', guest TEXT COLLATE "C" NOT NULL DEFAULT '',
  ssh_port TEXT COLLATE "C" NOT NULL DEFAULT '', mode TEXT COLLATE "C" NOT NULL DEFAULT '',
  last_connected TEXT COLLATE "C" NOT NULL DEFAULT '', product TEXT COLLATE "C" NOT NULL DEFAULT '',
  version TEXT COLLATE "C" NOT NULL DEFAULT '', updated_at TEXT COLLATE "C" NOT NULL);
CREATE TABLE aliases(alias TEXT COLLATE "C" PRIMARY KEY, host TEXT COLLATE "C" NOT NULL);
CREATE TABLE changes(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, host TEXT COLLATE "C" NOT NULL,
  date TEXT COLLATE "C" NOT NULL, time TEXT COLLATE "C" NOT NULL, who TEXT COLLATE "C" NOT NULL,
  headline TEXT COLLATE "C" NOT NULL, detail TEXT COLLATE "C" NOT NULL,
  rollback TEXT COLLATE "C" NOT NULL, flags TEXT COLLATE "C" NOT NULL);
CREATE INDEX changes_host ON changes(host);
CREATE INDEX changes_date ON changes(date, time);
CREATE TABLE todos(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, host TEXT COLLATE "C" NOT NULL,
  text TEXT COLLATE "C" NOT NULL, open INTEGER NOT NULL);
CREATE INDEX todos_host ON todos(host);
CREATE TABLE links(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, src TEXT COLLATE "C" NOT NULL,
  dst TEXT COLLATE "C" NOT NULL, label TEXT COLLATE "C" NOT NULL);
CREATE TABLE audits(
  snapshot TEXT COLLATE "C" NOT NULL, host TEXT COLLATE "C" NOT NULL,
  key TEXT COLLATE "C" NOT NULL, value TEXT COLLATE "C" NOT NULL);
CREATE INDEX audits_snapshot ON audits(snapshot);
CREATE TABLE sessions(
  id TEXT COLLATE "C" PRIMARY KEY, "user" TEXT COLLATE "C" NOT NULL,
  host TEXT COLLATE "C" NOT NULL, workstation TEXT COLLATE "C" NOT NULL,
  started_at TEXT COLLATE "C" NOT NULL, last_beat TEXT COLLATE "C" NOT NULL,
  ended_at TEXT COLLATE "C");
CREATE TABLE claims(
  host TEXT COLLATE "C" PRIMARY KEY, "user" TEXT COLLATE "C" NOT NULL,
  note TEXT COLLATE "C" NOT NULL, since TEXT COLLATE "C" NOT NULL);
CREATE TABLE guard(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "user" TEXT COLLATE "C" NOT NULL,
  at TEXT COLLATE "C" NOT NULL, reason TEXT COLLATE "C" NOT NULL);
CREATE TABLE eol(product TEXT COLLATE "C" PRIMARY KEY, fetched TEXT COLLATE "C" NOT NULL, body BYTEA NOT NULL);
CREATE TABLE jobs(
  name TEXT COLLATE "C" PRIMARY KEY, last_run TEXT COLLATE "C" NOT NULL,
  ok INTEGER NOT NULL, result TEXT COLLATE "C" NOT NULL);
